#!/usr/bin/env python3
"""Generate the Upkie joystick-demo course (uneven fields, ramps, a 1 cm step, a one-wheel ramp) as a MuJoCo module.

The uneven fields reuse generate_uneven_terrain.py with the tile style of config/terrains/upkie; the layout is
config/terrains/upkie/course_params.yaml. MuJoCo only: the MPC uses no terrain map, so no RViz model is generated.
"""

import argparse
import math
from pathlib import Path
import sys
import xml.etree.ElementTree as ET

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
import generate_uneven_terrain as uneven  # noqa: E402

ROOT = Path(__file__).resolve().parents[3]
COLORS = {"ramp": "0.85 0.9 1 1", "plateau": "0.9 0.9 0.9 1", "step_high": "1 0.9 0.8 1"}


def build_mjcf(config, params_dir, source="config/terrains/upkie/course_params.yaml", model="upkie_course"):
    """`source` names the parameter file in the generated comment. A field's optional `tiles` overrides the course's
    tile style; a plateau's optional `y: [y0, y1]` narrows it (default full width), like a ramp's; a ramp's or
    plateau's optional `rgba` overrides its colour."""
    half_width, friction = config["half_width"], uneven.fmt(config["friction"])
    root = ET.Element("mujoco", model=model)
    root.append(ET.Comment(f" Generated by generate_upkie_course.py; edit {source}. "))
    world = ET.SubElement(root, "worldbody")
    for field in config["uneven_fields"]:
        x0, x1 = field["x"]
        tile = yaml.safe_load((params_dir / field.get("tiles", config["tiles"])).read_text())["uneven_terrain"]
        tile.update(size=[x1 - x0, 2 * half_width], grid=[round((x1 - x0) / 0.25), round(2 * half_width / 0.25)],
                    seed=field["seed"])
        tile["base"]["pos"] = [(x0 + x1) / 2, 0.0, 0.0]
        uneven.validate(tile)
        body = ET.SubElement(world, "body", name=field["name"], pos=uneven.fmt(tile["base"]["pos"]))
        for block in uneven.generate_blocks(tile, uneven.generate_heights(tile)):
            ET.SubElement(body, "geom", name=f"{field['name']}_{block['name']}", type="box", pos=uneven.fmt(block["pos"]),
                          size=uneven.fmt([v / 2 for v in block["size"]]), material="studio_terrain", rgba="1 1 1 1",
                          friction=friction)
    thickness = 0.05
    for ramp in config["ramps"]:
        (x0, x1), (z0, z1) = ramp["x"], ramp["z"]
        y0, y1 = ramp.get("y", [-half_width, half_width])
        length, angle = math.hypot(x1 - x0, z1 - z0), math.atan2(z1 - z0, x1 - x0)
        # A slab rotated about y whose top face runs from (x0, z0) to (x1, z1).
        center = [(x0 + x1) / 2 + thickness * math.sin(angle), (y0 + y1) / 2, (z0 + z1) / 2 - thickness * math.cos(angle)]
        ET.SubElement(world, "geom", name=ramp["name"], type="box", pos=uneven.fmt(center),
                      size=uneven.fmt([length / 2, (y1 - y0) / 2, thickness]), euler=uneven.fmt([0, -angle, 0]),
                      material="studio_terrain", rgba=ramp.get("rgba", COLORS["ramp"]), friction=friction)
    for plateau in config["plateaus"]:
        (x0, x1), top = plateau["x"], plateau["top"]
        y0, y1 = plateau.get("y", [-half_width, half_width])
        ET.SubElement(world, "geom", name=plateau["name"], type="box",
                      pos=uneven.fmt([(x0 + x1) / 2, (y0 + y1) / 2, (top - 0.1) / 2]),
                      size=uneven.fmt([(x1 - x0) / 2, (y1 - y0) / 2, (top + 0.1) / 2]), material="studio_terrain",
                      rgba=plateau.get("rgba", COLORS.get(plateau["name"], COLORS["plateau"])),
                      friction=friction)
    return root


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--params", type=Path, default=ROOT / "config/terrains/upkie/course_params.yaml")
    parser.add_argument("--mjcf", type=Path, default=ROOT / "description/mujoco/terrains/upkie_course.xml")
    parser.add_argument("--check", action="store_true", help="verify the generated file without writing")
    args = parser.parse_args()
    config = yaml.safe_load(args.params.read_text())["upkie_course"]
    params = args.params.resolve()
    source = params.relative_to(ROOT) if params.is_relative_to(ROOT) else params.name
    content = uneven.xml_text(build_mjcf(config, params.parent, source, args.mjcf.stem))
    if args.check:
        if not args.mjcf.is_file() or args.mjcf.read_text() != content:
            parser.error(f"stale generated file: {args.mjcf}")
    else:
        args.mjcf.write_text(content)
        print("wrote", args.mjcf)


if __name__ == "__main__":
    main()
