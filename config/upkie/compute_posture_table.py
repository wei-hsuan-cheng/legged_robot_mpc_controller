#!/usr/bin/env python3
"""Balanced symmetric Upkie postures as a function of base height; writes the posture table YAML that
ocs2.reference.postureTableFile points at (default config/upkie/posture_table.yaml).

    pip install mujoco numpy          # offline tool; not needed at run time
    python3 config/upkie/compute_posture_table.py [--min 0.125] [--max 0.355] [--step 0.01] [--output FILE]

In the ros_jazzy container, config/upkie/regenerate.sh posture runs this in the offline venv.
For each base height h the trunk is level at (0, 0, h), both tires touch the floor (tire centre at the
radius) and the tire contact sits under the whole-robot centre of mass, so the posture is a static
balance point of the wheeled inverted pendulum. Right joints mirror the left ones. Solved by Newton
iteration on (hip, knee) from the previous height, starting at the 0.30 m defaultJointState.
The maximum height is chosen with a knee-bend margin: at a straight knee (about 0.34 m) the leg is
singular and the knee servo chatters.
"""

import argparse
import math
import xml.etree.ElementTree as ET
from pathlib import Path

import mujoco
import numpy as np

HERE = Path(__file__).resolve().parent
MJCF = HERE / ".." / ".." / "description" / "mujoco" / "robots" / "upkie" / "upkie.xml"


def tire_radius():
    """Circumradius of upkie.xml's tire collision prism (the wheel radius the MPC and the estimator use)."""
    mesh = next(m for m in ET.parse(MJCF).getroot().iter("mesh") if m.get("name") == "tire_collision")
    v = [float(x) for x in mesh.get("vertex").split()]
    return max(math.hypot(v[i], v[i + 1]) for i in range(0, len(v), 3))


RADIUS = tire_radius()
# The leg posture balanced at 0.30 m with the original 0.055 m wheels; a larger wheel raises the same posture by the
# radius difference, so the Newton start keeps the posture and shifts the height.
NOMINAL = (round(0.30 + RADIUS - 0.055, 6), -0.6021396734839873, -0.9655142016056263)


class Model:
    def __init__(self):
        self.m = mujoco.MjModel.from_xml_path(str(MJCF))
        self.d = mujoco.MjData(self.m)
        self.qadr = {n: self.m.joint(n).qposadr[0] for n in ("left_hip", "left_knee", "left_wheel", "right_hip", "right_knee", "right_wheel")}
        self.tire = self.m.geom("left_foot_collision").id

    def residual(self, height, hip, knee):
        d = self.d
        d.qpos[:] = 0.0
        d.qpos[:3] = (0.0, 0.0, height)
        d.qpos[3:7] = (1.0, 0.0, 0.0, 0.0)
        d.qpos[self.qadr["left_hip"]], d.qpos[self.qadr["left_knee"]] = hip, knee
        d.qpos[self.qadr["right_hip"]], d.qpos[self.qadr["right_knee"]] = -hip, -knee
        mujoco.mj_kinematics(self.m, d)
        mujoco.mj_comPos(self.m, d)
        tire = d.geom_xpos[self.tire]
        com = d.subtree_com[1]
        return np.array([tire[2] - RADIUS, tire[0] - com[0]])

    def solve(self, height, hip, knee):
        x = np.array([hip, knee])
        for _ in range(50):
            r = self.residual(height, *x)
            if np.linalg.norm(r) < 1e-10:
                return x
            J = np.empty((2, 2))
            for i in range(2):
                dx = np.zeros(2)
                dx[i] = 1e-7
                J[:, i] = (self.residual(height, *(x + dx)) - r) / 1e-7
            x = x - np.linalg.solve(J, r)
        raise RuntimeError(f"no balanced posture at height {height:.3f} m")


JOINTS = ("left_hip", "left_knee", "left_wheel", "right_hip", "right_knee", "right_wheel")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    # The sit-down crouch and the stand-up catch start at 0.125 m: knee bend 2.43 rad, the deepest fold the 0.080 m
    # tire clears the femur at.
    parser.add_argument("--min", type=float, default=0.125)
    parser.add_argument("--max", type=float, default=round(0.33 + RADIUS - 0.055, 6))
    parser.add_argument("--step", type=float, default=0.01)
    parser.add_argument("--output", type=Path, default=HERE / "posture_table.yaml")
    args = parser.parse_args()

    model = Model()
    check = model.solve(*NOMINAL)
    heights = np.round(np.arange(args.min, args.max + 1e-9, args.step), 4)
    solutions = {}
    for direction in (heights[heights >= NOMINAL[0]], heights[heights < NOMINAL[0]][::-1]):
        guess = check
        for h in direction:
            guess = model.solve(h, *guess)
            solutions[h] = guess
    lines = [
        "# Balanced symmetric Upkie postures by base height: level trunk, both tires on the floor, tire contact under",
        "# the whole-robot CoM. The MPC interpolates its joint posture reference at the target base height and clamps",
        "# targets to [first, last] height; ocs2.reference.minBaseHeight/maxBaseHeight and bringUp.sitDownHeight must",
        "# lie inside. Generated by config/upkie/compute_posture_table.py (config/upkie/regenerate.sh posture); do not",
        "# edit by hand.",
        f"# tire radius {RADIUS:.4f} m (upkie.xml tire_collision); check at {NOMINAL[0]:.3f} m: hip {check[0]:+.6f} "
        f"knee {check[1]:+.6f} (defaultJointState {NOMINAL[1]:+.6f} {NOMINAL[2]:+.6f})",
        "posture_table:",
        "  joint_names: [" + ", ".join(JOINTS) + "]",
        "  heights: [" + ", ".join(f"{h:.3f}" for h in heights) + "]",
        "  joint_states:",
    ]
    for h in heights:
        hip, knee = solutions[h]
        lines.append(f"    - [{hip:.6f}, {knee:.6f}, 0.0, {-hip:.6f}, {-knee:.6f}, 0.0]  # {h:.3f} m, knee bend {abs(knee):.3f} rad")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines) + "\n")
    print(f"wrote {args.output}: {len(heights)} heights {heights[0]:.3f}-{heights[-1]:.3f} m, tire radius {RADIUS:.4f} m")


if __name__ == "__main__":
    main()
